import { z } from "zod";

export const DocumentRelationSchema = z.object({
  targetDocumentNumber: z.string().min(3),
  targetTitle: z.string().min(3),
  relationType: z.enum(["PADRE", "HIJO", "RELACIONADO", "DERIVA_DE", "COMPLEMENTA", "SUSTITUYE"]),
  description: z.string().optional(),
});

export const MasterCatalogDocumentSchema = z.object({
  documentId: z.string().min(2, "El ID del documento es obligatorio"),
  documentNumber: z.string().regex(/^REN-DOC-\d{3}$/, "El número de documento debe tener formato 'REN-DOC-XXX'"),
  title: z.string().min(3, "El título debe tener al menos 3 caracteres"),
  shortTitle: z.string().min(2, "El título corto es obligatorio"),
  hierarchyLevel: z.enum([
    "NIVEL_1_FUNDAMENTAL",
    "NIVEL_2_CONSTITUCIONAL_CORPORATIVO",
    "NIVEL_3_DOCTRINAL",
    "NIVEL_4_MANUAL_INSTITUCIONAL",
    "NIVEL_5_REGLAMENTO",
    "NIVEL_6_PROGRAMA_ACADEMICO",
    "NIVEL_7_PROCEDIMIENTO",
    "NIVEL_8_FORMULARIO",
    "NIVEL_9_CERTIFICADO_CREDENCIAL",
    "NIVEL_10_REGISTRO_EXPEDIENTE",
  ]),
  category: z.enum([
    "FUNDAMENTAL",
    "CORPORATIVO",
    "DOCTRINA",
    "GOBIERNO",
    "MINISTERIAL",
    "MEMBRESIA",
    "DISCIPULADO",
    "LIDERAZGO",
    "ACADEMICO",
    "FINANZAS",
    "ADMINISTRACION",
    "PROTECCION",
    "ETICA",
    "CULTO",
    "CEREMONIAS",
    "MISIONES",
    "INFANTIL",
    "JUVENIL",
    "EVANGELISMO",
    "TECNOLOGIA",
    "LEGAL",
    "FORMULARIOS",
    "CERTIFICADOS",
    "REGISTROS",
    "EXPEDIENTES",
  ]),
  subcategory: z.string().min(2),
  description: z.string().min(5),
  owner: z.string().min(2),
  author: z.string().min(2),
  responsibleArea: z.string().min(2),
  status: z.enum([
    "PLANIFICADO",
    "BORRADOR",
    "EN_REVISION",
    "CANDIDATO_APROBACION",
    "APROBACION_PENDIENTE",
    "ADOPTADO",
    "SUPERADO",
    "ARCHIVADO",
    "RECHAZADO",
    "DEVUELTO_REVISION",
  ]),
  version: z.string().regex(/^\d+\.\d+$/, "La versión debe tener formato MAYOR.MENOR"),
  language: z.enum(["es", "en"]),
  confidentiality: z.enum(["PUBLICO", "INTERNO_CONGREGACION", "CONFIDENCIAL_LIDERAZGO", "RESTRINGIDO_GOBIERNO"]),
  
  approvalAuthority: z
    .enum([
      "PASTOR_FUNDADOR",
      "CONSEJO_GOBIERNO",
      "CONSEJO_MINISTERIAL",
      "DIRECCION_ACADEMICA",
      "ADMINISTRACION_GENERAL",
      "COMITE_ETICA_PROTECCION",
    ])
    .optional(),
  proposedApprovalAuthority: z
    .enum([
      "PASTOR_FUNDADOR",
      "CONSEJO_GOBIERNO",
      "CONSEJO_MINISTERIAL",
      "DIRECCION_ACADEMICA",
      "ADMINISTRACION_GENERAL",
      "COMITE_ETICA_PROTECCION",
    ])
    .optional(),
  approvalAuthorityStatus: z.enum(["DEFINIDA", "PROPUESTA", "PENDIENTE_DEFINIR"]),
  signatureRequirement: z.enum([
    "NO_SIGNATURE_REQUIRED",
    "SINGLE_SIGNATURE",
    "MULTIPLE_SIGNATURES",
    "INSTITUTIONAL_RESOLUTION",
    "DOCTRINAL_ADOPTION",
  ]),
  requiredReviews: z.array(
    z.enum([
      "REVISION_BIBLICA",
      "REVISION_DOCTRINAL",
      "REVISION_ACADEMICA",
      "REVISION_LEGAL",
      "REVISION_ADMINISTRATIVA",
      "REVISION_FINANCIERA",
      "REVISION_PROTECCION",
    ])
  ),

  parentDocument: z.string().optional(),
  relatedDocuments: z.array(DocumentRelationSchema).default([]),
  requiredFor: z.array(z.string()).optional(),

  createdAt: z.string(),
  updatedAt: z.string(),
  adoptedAt: z.string().optional(),
  effectiveDate: z.string().optional(),
  supersedes: z.string().optional(),
  supersededBy: z.string().optional(),
  reviewFrequencyMonths: z.number().int().min(1),
  nextReviewDate: z.string().optional(),

  documentDigestSha256: z.string().length(64).optional(),
  tags: z.array(z.string()).default([]),
});
