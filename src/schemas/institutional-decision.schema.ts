import { z } from "zod";

export const DecisionOptionSchema = z.object({
  optionKey: z.string().min(1),
  title: z.string().min(2),
  description: z.string().min(5),
  pros: z.array(z.string()).optional(),
  cons: z.array(z.string()).optional(),
  isRecommended: z.boolean().optional(),
});

export const DecisionRecommendationSchema = z.object({
  summary: z.string().min(5),
  source: z.enum([
    "ANALISIS_BIBLICO",
    "ANALISIS_INSTITUCIONAL",
    "ANALISIS_ACADEMICO",
    "ANALISIS_LEGAL",
    "ANALISIS_ADMINISTRATIVO",
  ]),
  justification: z.string().min(10),
});

export const InstitutionalDecisionSchema = z.object({
  decisionId: z.string().min(2),
  decisionNumber: z.string().regex(/^DEC-(DEF|PEND|PROP|SUP|RSK)?-?\d{3}$/, "Formato de decisión institucional (ej: DEC-DEF-001, DEC-DEF-177)"),
  title: z.string().min(3),
  question: z.string().min(5),
  category: z.enum([
    "DOCTRINAL",
    "ECLESIOLOGICA",
    "GOBIERNO",
    "CORPORATIVA",
    "LEGAL",
    "FINANCIERA",
    "MINISTERIAL",
    "ACADEMICA",
    "ADMINISTRATIVA",
    "MEMBRESIA",
    "DISCIPULADO",
    "PROTECCION",
    "CULTO",
    "MISIONES",
    "TECNOLOGIA",
    "RIESGOS",
    "SEGURIDAD",
  ]),
  description: z.string().min(10),
  options: z.array(DecisionOptionSchema).optional(),
  recommendation: DecisionRecommendationSchema.optional(),
  decision: z.string().optional(),
  decisionStatus: z.enum([
    "DEFINIDA",
    "PENDIENTE",
    "NO_RESUELTA",
    "DECIDIDA",
    "EN_ANALISIS",
    "PROPUESTA",
    "RECHAZADA",
    "SUPERADA",
    "REQUIERE_REVISION_LEGAL",
  ]),
  decisionState: z.enum(["DEFINIDA", "PENDIENTE", "NO_RESUELTA"]).default("DEFINIDA"),
  documentState: z.enum([
    "NO_ASIGNADO",
    "PLANIFICADO",
    "EN_REDACCION",
    "EN_REVISION",
    "CANDIDATO_ADOPCION",
    "ADOPTADO",
    "SUPERADO",
    "ARCHIVADO",
  ]).default("PLANIFICADO"),
  legalState: z.enum([
    "NO_REQUIERE_REVISION_LEGAL",
    "REQUIERE_REVISION_LEGAL",
    "REVISION_LEGAL_EN_CURSO",
    "REVISION_LEGAL_COMPLETADA",
  ]).default("NO_REQUIERE_REVISION_LEGAL"),
  documentTarget: z.enum([
    "ARTICLES",
    "CONSTITUCION",
    "BYLAWS",
    "DOCTRINA",
    "MANUAL",
    "REGLAMENTO",
    "SOP",
    "MULTICAPA",
    "PENDIENTE_DEFINIR",
  ]).default("CONSTITUCION"),
  decisionAuthority: z.string().min(2),
  authorityStatus: z.enum(["DEFINIDA", "PROPUESTA", "PENDIENTE"]),
  decidedBy: z.string().optional(),
  decidedAt: z.string().optional(),
  rationale: z.string().optional(),
  biblicalBasis: z.array(z.string()).default([]),
  legalBasis: z.array(z.string()).default([]),
  affectedDocuments: z.array(z.string()).default([]),
  dependencies: z.array(z.string()).default([]),
  supersedesDecision: z.string().optional(),
  supersededBy: z.string().optional(),
  notes: z.string().optional(),
  createdAt: z.string(),
  updatedAt: z.string(),
});
