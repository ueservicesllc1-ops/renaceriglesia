export function generateFullBylawsMarkdown(): string {
  const doc = FULL_BYLAWS_DRAFT;
  let md = `# ${doc.title}\n\n`;
  md += `**Entidad Corporativa:** ${doc.organization}\n`;
  md += `**Denominación Ministerial:** ${doc.publicName}\n`;
  md += `**Lema:** ${doc.tagline}\n`;
  md += `**Pastor Fundador:** ${doc.founder}\n`;
  md += `**Código:** ${doc.documentNumber}\n`;
  md += `**Versión:** v${doc.version}\n`;
  md += `**Estado Institucional:** BORRADOR EN REDACCIÓN — NO ADOPTADA\n`;
  md += `**Estado Legal:** REQUIERE REVISIÓN LEGAL (New Jersey Nonprofit Corporation Act & IRC § 501(c)(3))\n\n`;
  md += `> **AVISO LEGAL OBLIGATORIO:** ${doc.legalNotice}\n\n`;
  md += `---\n\n`;

  md += `## ${doc.preamble.title}\n\n`;
  md += `${doc.preamble.fullText}\n\n`;
  md += `---\n\n`;

  for (const t of doc.titles) {
    md += `## ${t.romanNumeral} — ${t.title}\n\n`;
    md += `*${t.summary}*\n\n`;

    for (const art of t.articles) {
      md += `### ARTÍCULO ${art.articleNumber} — ${art.title}\n\n`;
      md += `**Objetivo Corporativo:** ${art.objective}\n\n`;
      md += `${art.fullText}\n\n`;

      if (art.decisionIds && art.decisionIds.length > 0) {
        md += `*Decisiones Institucionales Vinculadas:* ${art.decisionIds.join(", ")}\n\n`;
      }
      if (art.dependencies && art.dependencies.length > 0) {
        md += `*Documentos Relacionados:* ${art.dependencies.join(", ")}\n\n`;
      }
      if (art.legalReviewRequired) {
        md += `> ⚠️ **REQUIERE REVISIÓN LEGAL:** ${art.legalReviewNotes || "Materia estatutaria civil sujeta a dictamen de abogado colegiado en New Jersey."}\n\n`;
      }
      if (art.pendingDefinitionNotes) {
        md += `> ⏳ **PENDIENTE DE DEFINICIÓN:** ${art.pendingDefinitionNotes}\n\n`;
      }
    }
    md += `---\n\n`;
  }

  md += `## DISPOSICIONES FINALES Y NOTA DE ESTADO\n\n`;
  md += `1. **Naturaleza del Documento:** Los presentes Bylaws de RENACER CHURCH, INC. (REN-DOC-003 v0.1) se encuentran en estado de **BORRADOR EN REDACCIÓN** y **NO HAN SIDO ADOPTADOS**.\n`;
  md += `2. **Subordinación Legal:** Este instrumento se subordina al Certificate of Incorporation presentado ante el Estado de New Jersey y a las leyes aplicables.\n`;
  md += `3. **Jerarquía Institucional:** Los Bylaws prevalecen sobre los manuales, reglamentos y procedimientos operativos, y operan en plena armonía con la Constitución (REN-DOC-002) y la Declaración de Fe (REN-DOC-001).\n`;

  return md;
}
